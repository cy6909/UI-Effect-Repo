export function titleZh(title, category) {
  let translated = title;
  for (const [en, zh] of Object.entries(phrases).sort((a, b) => b[0].length - a[0].length)) {
    const escaped = en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    translated = translated.replace(new RegExp(`\\b${escaped}\\b`, 'g'), zh);
  }
  return /[\u3400-\u9fff]/.test(translated) ? translated : `${translated} · ${categoryZh[category]}`;
}
